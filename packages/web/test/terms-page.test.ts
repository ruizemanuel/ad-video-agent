import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { describe, expect, it } from 'vitest';
import TermsPage from '../src/app/terms/page';

// The words, without the markup between them.
const text = renderToStaticMarkup(createElement(TermsPage))
  .replace(/<[^>]+>/g, ' ')
  .replace(/&#x27;|&#39;/g, "'")
  .replace(/\s+/g, ' ');

describe('the terms page', () => {
  it.each([
    ['the person who orders owns the site or may use its brand', /own the site you send, or have permission to use its brand/i],
    ['the person is 18 or older', /18 years of age or older/i],
    ['every claim comes from the site', /every claim in the video comes from the site/i],
    ['the music is made by AI and carries SynthID', /music is generated by AI.*SynthID/i],
    ['a refund only when the order is not delivered, to the paying address', /refund only if the order is not delivered.*address that paid/i],
    ['links last 30 days and the order is deleted after 30 days', /links work for 30 days.*deleted 30 days/i],
  ])('says %s', (_clause, words) => {
    expect(text).toMatch(words);
  });
});
